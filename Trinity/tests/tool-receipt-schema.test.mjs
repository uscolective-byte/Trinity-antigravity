import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {Miniflare,convertV4MiniflareOptions} from 'miniflare';
import {ToolExecutor} from '../src/lib/trinity-tool-executor.js';
import {D1} from '../src/lib/d1.js';
import {Dispatcher} from '../src/services/dispatcher.js';

test('executor receipts obey the real core schema and preserve large JSON evidence',async()=>{
  const mf=new Miniflare(convertV4MiniflareOptions({workers:[{name:'fixture',modules:true,script:'export default {fetch(){return new Response("ok")}}',d1Databases:{DB:'receipt-schema'}}]}));
  try{
    const db=await mf.getD1Database('DB','fixture');
    const source=await readFile(new URL('../migrations/0052_core_agent_runtime.sql',import.meta.url),'utf8');
    for(const sql of source.split(/;\s*(?:\r?\n|$)/).map(value=>value.trim()).filter(Boolean)) await db.prepare(sql).run();
    await db.prepare("INSERT INTO core_agent_runs(id,idempotency_key,input_hash,trace_id,prompt,status) VALUES('run-1','key-1','hash-1','trace-1','Read fixture','running')").run();
    const executor=new ToolExecutor({DB:db});
    const output={success:true,text:'Evidence '.repeat(2000)};
    assert.equal(await executor._writeReceipt('run-1',0,'read','success','receipt-1',{},output),true);
    assert.equal(await executor._writeReceipt('run-1',1,'read','exception','receipt-2',{}, {error:'provider failure'}),true);
    const rows=(await db.prepare('SELECT status,output_json FROM core_tool_receipts ORDER BY step').all()).results;
    assert.equal(rows[0].status,'completed');
    assert.deepEqual(JSON.parse(rows[0].output_json),output);
    assert.equal(rows[1].status,'failed');
    assert.equal(await executor._writeReceipt('nonexistent-run',0,'read','success','receipt-3',{},output),false);
    assert.equal((await db.prepare('SELECT count(*) AS count FROM core_tool_receipts').first()).count,2);
    const registry=await readFile(new URL('../migrations/0060_tool_calling_registry.sql',import.meta.url),'utf8');
    for(const sql of registry.split(/;\s*(?:\r?\n|$)/).map(value=>value.trim()).filter(Boolean)) await db.prepare(sql).run();
    await db.prepare("INSERT INTO trinity_tool_registry(tool_id,name,handler_type,handler_target,enabled) VALUES('read','Read','service','CORE',1)").run();
    const storage=new D1(db);
    assert.equal(await storage.recordToolSuccess('read',12,{runId:'run-1',step:2,receiptId:'receipt-4',input:output,output}),true);
    const saved=await db.prepare("SELECT input_json,output_json FROM core_tool_receipts WHERE receipt_id='receipt-4'").first();
    assert.deepEqual(JSON.parse(saved.input_json),output);
    assert.deepEqual(JSON.parse(saved.output_json),output);
    assert.equal((await storage.getTool('read')).success_count,1);
    let calls=0;
    const liveExecutor=new ToolExecutor({DB:db,CORE:{fetch:async()=>{calls++;return Response.json(output);}}});
    const executed=await liveExecutor.execute('read',{});
    assert.equal(executed.status,'success');
    assert.equal((await db.prepare('SELECT status FROM core_agent_runs WHERE id=?').bind(executed.run_id).first()).status,'completed');
    assert.deepEqual(JSON.parse((await db.prepare('SELECT output_json FROM core_tool_receipts WHERE receipt_id=?').bind(executed.receipt_id).first()).output_json),output);
    assert.equal((await liveExecutor.execute('read',{},'missing-run')).error,'ACTIVE_RUN_REQUIRED');
    assert.equal(calls,1);
    liveExecutor.serviceMap.CORE={fetch:async()=>Response.json({status:'running',job_id:'pending-job'})};
    const pending=await liveExecutor.execute('read',{});
    assert.equal(pending.status,'running');
    assert.equal((await db.prepare('SELECT status FROM core_agent_runs WHERE id=?').bind(pending.run_id).first()).status,'running');
    await assert.rejects(()=>storage.recordToolSuccess('read',12,{runId:'missing',step:0,receiptId:'receipt-5',input:{},output}),/FOREIGN KEY/);
    assert.equal((await storage.getTool('read')).success_count,2);
    assert.equal(await storage.recordToolError('read',output,'actual failure',{runId:'run-1',step:3,receiptId:'failed-receipt'}),true);
    const failed=await db.prepare("SELECT run_id,step,status,input_json FROM core_tool_receipts WHERE receipt_id='failed-receipt'").first();
    assert.equal(failed.run_id,'run-1');
    assert.equal(failed.step,3);
    assert.equal(failed.status,'failed');
    assert.deepEqual(JSON.parse(failed.input_json),output);
    assert.equal(await storage.recordToolError('read',{},'no execution identity'),false);
    assert.equal(await storage.recordToolError('read',{},'missing run',{runId:'absent',step:0,receiptId:'not-stored'}),false);
    assert.equal((await storage.getTool('read')).error_count,1);
    storage.log=async()=>{};
    let dispatched=0;
    const dispatcher=new Dispatcher({DB:db,CORE:{fetch:async()=>{dispatched++;return Response.json({success:true,result:'dispatcher fixture'});}}},storage);
    const dispatchResult=await dispatcher.executeTool('read',{});
    assert.equal(dispatchResult.status,'success');
    assert.equal((await db.prepare('SELECT status FROM core_agent_runs WHERE id=?').bind(dispatchResult.run_id).first()).status,'completed');
    const dispatchReceipt=await db.prepare('SELECT run_id,status FROM core_tool_receipts WHERE receipt_id=?').bind(dispatchResult.receipt_id).first();
    assert.equal(dispatchReceipt.run_id,dispatchResult.run_id);
    assert.equal(dispatchReceipt.status,'completed');
    assert.equal((await dispatcher.executeTool('read',{},'absent')).error,'ACTIVE_RUN_REQUIRED');
    assert.equal(dispatched,1);
    const pipeline=await dispatcher.executePipeline([{tool:'read'},{tool:'read'}]);
    assert.equal(pipeline.completed,true);
    assert.equal((await db.prepare('SELECT count(*) AS count FROM core_tool_receipts WHERE run_id=?').bind(pipeline.run_id).first()).count,2);
    assert.equal((await db.prepare('SELECT status FROM core_agent_runs WHERE id=?').bind(pipeline.run_id).first()).status,'completed');
  }finally{await mf.dispose();}
});
