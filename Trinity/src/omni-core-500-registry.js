export function getOmniCoreImprovement(idOrNumber) {
  if (typeof idOrNumber === 'number') {
    return OMNI_CORE_500_IMPROVEMENTS.find(item => item.number === idOrNumber) || null;
  }
  const normalized = String(idOrNumber || '').trim().toUpperCase();
  return OMNI_CORE_500_IMPROVEMENTS.find(item => item.id === normalized || String(item.number) === normalized) || null;
}

export function listOmniCoreImprovementsByLayer(layer) {
  const normalized = String(layer || '').trim().toUpperCase();
  return OMNI_CORE_500_IMPROVEMENTS.filter(item => item.layer.includes(normalized));
}

export function getOmniCore500Summary() {
  const byLayer = {};
  for (const item of OMNI_CORE_500_IMPROVEMENTS) {
    byLayer[item.layer] = (byLayer[item.layer] || 0) + 1;
  }
  return {
    total_improvements: OMNI_CORE_500_IMPROVEMENTS.length,
    part_1_system_desktop_250: 250,
    part_2_architecture_omni_core_250: 250,
    foundational_pillars_75: OMNI_CORE_75_FOUNDATIONAL_PILLARS.length,
    by_layer: byLayer
  };
}
